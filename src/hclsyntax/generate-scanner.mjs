// Development-only translation of the pinned HCL Ragel tables, not a Go transpiler.
// Run: node src/hclsyntax/generate-scanner.mjs <hcl checkout>
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
const out = dirname(fileURLToPath(import.meta.url));
const [hcl] = process.argv.slice(2);
if (!hcl) throw new Error('Pass the pinned HCL source directory');
const revision = '00057cf06d7b38a3f89e6e54d622eee98322b314';
const mpl = `/*! @license MPL-2.0\n * Copyright IBM Corp. 2014, 2025\n * Translated source: https://github.com/hashicorp/hcl/tree/${revision}\n * Covered source and modifications are available in this Reylo fork. See licenses/hashicorp-hcl-MPL-2.0.txt.\n */`;
for (const [source, destination, prefix, notice] of [
  [resolve(hcl, 'hclsyntax/scan_tokens.go'), 'scanner-tables.ts', '_hcltok', `${mpl}\n// HCL revision ${revision}, hclsyntax/scan_tokens.go.`],
  [resolve(hcl, 'hclsyntax/scan_string_lit.go'), 'string-literal-tables.ts', '_hclstrtok', `${mpl}\n// HCL revision ${revision}, hclsyntax/scan_string_lit.go.`],
]) {
  const input = readFileSync(source, 'utf8');
  let output = `${notice}\n// Generated by generate-scanner.mjs. Do not edit the transition tables.\n\n`;
  for (const match of input.matchAll(/var (_\w+) \[\](\w+) = \[\]\w+\{([\s\S]*?)\n\}/g)) {
    if (!match[1].startsWith(prefix)) continue;
    const kind = match[2] === 'byte' ? 'Uint8Array' : match[2] === 'int16' ? 'Int16Array' : match[2] === 'uint16' ? 'Uint16Array' : 'Int32Array';
    output += `export const ${match[1].slice(prefix.length + 1)} = new ${kind}([${match[3]}\n]);\n\n`;
  }
  for (const match of input.matchAll(/const (\w+) int = (\d+)/g)) {
    output += `export const ${match[1].replace(/^hcltok_|^hclstrtok_/, '')} = ${match[2]};\n`;
  }
  writeFileSync(resolve(out, destination), output);
}
