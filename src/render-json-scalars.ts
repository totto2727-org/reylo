// MySQL stores no infinity or NaN, and SQLite NUMERIC can be returned as text.
const mysqlJson: Record<string, string> = { ...json, float4: "number", float8: "number", numeric: "number" };
const sqliteJson: Record<string, string> = { bool: "boolean", int8: "number", integer: "number", numeric: "number | string", real: "number", text: "string" };

const tables = new Map<Dialect, Record<string, string>>([["mysql", mysqlJson], ["sqlite", sqliteJson]]);

export const jsonScalar = (name: string, dialect: Dialect): string => {
  const types = tables.get(dialect) ?? json;
  const parts = name.split("|").map((part) => types[part] ?? JSON_TYPE);
  if (parts.includes(JSON_TYPE)) {return JSON_TYPE;}
  return [...new Set(parts.flatMap((part) => part.split(" | ")))].join(" | ");
};
